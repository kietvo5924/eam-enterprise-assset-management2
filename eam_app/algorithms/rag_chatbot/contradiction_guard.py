"""
Contradiction Guard & Negation Safety Verifier (Rule 1, Rule 8).
Detects if LLM summary inverts or drops essential negative safety prohibitions
(e.g., 'DO NOT turn valve while running' -> 'turn valve while running' or drops 'CẤM').
If a contradiction risk is detected, rejects the generated summary and returns
the raw verbatim source quote with an amber/red border alert.
"""

import re
from typing import Dict, Any, List
from .constants import FORBIDDEN_NEGATION_TERMS


def check_negation_contradiction(generated_reply: str, source_content: str) -> Dict[str, Any]:
    """
    Checks whether safety-critical negative prohibitions in source_content
    are dropped or inverted in generated_reply.
    
    Args:
        generated_reply: The text generated by LLM/synthesizer.
        source_content: The original parent/child chunk text from documentation.
        
    Returns:
        dict: {
            'contradiction_detected': bool,
            'reason': str or None,
            'raw_verbatim_quote': str or None,
            'safe_reply': str
        }
    """
    if not source_content:
        return {
            'contradiction_detected': False,
            'reason': None,
            'raw_verbatim_quote': None,
            'safe_reply': generated_reply
        }

    lower_source = source_content.lower()
    lower_reply = generated_reply.lower()

    # Identify if source contains critical negative prohibitions
    source_prohibitions: List[str] = []
    for term in FORBIDDEN_NEGATION_TERMS:
        if term in lower_source:
            source_prohibitions.append(term)

    if not source_prohibitions:
        return {
            'contradiction_detected': False,
            'reason': None,
            'raw_verbatim_quote': None,
            'safe_reply': generated_reply
        }

    # Extract sentences containing prohibitions from source
    # Split by periods, exclamation marks, or newlines
    raw_sentences = re.split(r'[.\n!]+', source_content)
    prohibition_sentences = []
    for s in raw_sentences:
        s_clean = s.strip()
        s_lower = s_clean.lower()
        if any(term in s_lower for term in source_prohibitions):
            prohibition_sentences.append(s_clean)

    # Check if the generated reply preserves these prohibitions
    # A contradiction occurs if the generated reply mentions the action but drops the prohibition term
    contradiction_found = False
    failing_prohibition = ""

    for s in prohibition_sentences:
        s_lower = s.lower()
        # Extract key action words (words other than standard stop words and prohibition words)
        words = [w for w in re.findall(r'\b\w+\b', s_lower) if len(w) > 3 and w not in source_prohibitions]
        # If generated reply has key words of the prohibited action
        action_match_count = sum(1 for w in words if w in lower_reply)
        if len(words) > 0 and (action_match_count / len(words)) >= 0.5:
            # The reply talks about this action. Does it contain the prohibition term from this sentence?
            sentence_prohibitions = [term for term in source_prohibitions if term in s_lower]
            reply_has_prohibition = any(term in lower_reply for term in sentence_prohibitions)
            if not reply_has_prohibition:
                contradiction_found = True
                failing_prohibition = s
                break

    if contradiction_found and failing_prohibition:
        raw_verbatim_quote = f"> ⚠️ **CẢNH BÁO AN TOÀN QUAN TRỌNG (TRÍCH DẪN NGUYÊN VĂN TÀI LIỆU GỐC):**\n> \"{failing_prohibition}\""
        safe_reply = (
            f"{raw_verbatim_quote}\n\n"
            f"*(Hệ thống đã tự động khóa câu trả lời tóm tắt do phát hiện nguy cơ lược bỏ chỉ dẫn cấm đoán an toàn)*\n\n"
            f"{generated_reply}"
        )
        return {
            'contradiction_detected': True,
            'reason': f"Phát hiện nguy cơ lược bỏ/đảo ngược quy tắc an toàn: '{failing_prohibition}'",
            'raw_verbatim_quote': raw_verbatim_quote,
            'safe_reply': safe_reply
        }

    return {
        'contradiction_detected': False,
        'reason': None,
        'raw_verbatim_quote': None,
        'safe_reply': generated_reply
    }
